CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_user_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    room_id BIGINT NOT NULL,
    source_type VARCHAR(40) NOT NULL,
    source_id BIGINT NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    room_status_history_id BIGINT,
    maintenance_request_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ,

    CONSTRAINT fk_notifications_recipient_user
        FOREIGN KEY (recipient_user_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_actor_user
        FOREIGN KEY (actor_user_id) REFERENCES users (id),
    CONSTRAINT fk_notifications_room
        FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT fk_notifications_room_status_history
        FOREIGN KEY (room_status_history_id) REFERENCES room_status_history (id),
    CONSTRAINT fk_notifications_maintenance_request
        FOREIGN KEY (maintenance_request_id) REFERENCES maintenance_requests (id),
    CONSTRAINT uq_notifications_source_recipient
        UNIQUE (source_type, source_id, event_type, recipient_user_id),
    CONSTRAINT chk_notifications_source_type
        CHECK (source_type IN ('ROOM_STATUS_HISTORY', 'MAINTENANCE_REQUEST')),
    CONSTRAINT chk_notifications_event_type
        CHECK (event_type IN ('ROOM_CLEANED', 'MAINTENANCE_REPORTED')),
    CONSTRAINT chk_notifications_source_event_pair
        CHECK (
            (source_type = 'ROOM_STATUS_HISTORY' AND event_type = 'ROOM_CLEANED')
            OR (source_type = 'MAINTENANCE_REQUEST' AND event_type = 'MAINTENANCE_REPORTED')
        ),
    CONSTRAINT chk_notifications_source_reference
        CHECK (
            (event_type = 'ROOM_CLEANED'
                AND room_status_history_id IS NOT NULL
                AND maintenance_request_id IS NULL
                AND source_id = room_status_history_id)
            OR (event_type = 'MAINTENANCE_REPORTED'
                AND maintenance_request_id IS NOT NULL
                AND room_status_history_id IS NULL
                AND source_id = maintenance_request_id)
        )
);

CREATE INDEX idx_notifications_inbox_cursor
    ON notifications (recipient_user_id, created_at DESC, id DESC);

CREATE INDEX idx_notifications_unread_recipient
    ON notifications (recipient_user_id)
    WHERE read_at IS NULL;
