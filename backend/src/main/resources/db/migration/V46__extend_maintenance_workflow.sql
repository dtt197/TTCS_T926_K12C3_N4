            'MAINTENANCE_REPORTED', 'MAINTENANCE_REPAIR_COMPLETED',
            'MAINTENANCE_VERIFIED', 'MAINTENANCE_REPAIR_REJECTED', 'MAINTENANCE_CLEANED'))),
    ADD CONSTRAINT chk_notifications_source_reference CHECK (
        (source_type = 'ROOM_STATUS_HISTORY' AND room_status_history_id IS NOT NULL
            AND maintenance_request_id IS NULL AND source_id = room_status_history_id) OR
        (source_type = 'MAINTENANCE_REQUEST' AND maintenance_request_id IS NOT NULL
            AND room_status_history_id IS NULL AND source_id = maintenance_request_id));
