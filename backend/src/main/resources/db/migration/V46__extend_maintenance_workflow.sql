-- Nullable milestones deliberately support legacy rows in all four V44 states.
-- HOAN_TAT is terminal only after housekeeping cleaning in slice 3.
CREATE TABLE maintenance_request_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maintenance_request_id BIGINT NOT NULL REFERENCES maintenance_requests(id),
    action VARCHAR(40) NOT NULL,
    previous_status VARCHAR(30) NOT NULL,
    new_status VARCHAR(30) NOT NULL,
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    actor_name VARCHAR(150) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vendor_name VARCHAR(200),
    vendor_phone VARCHAR(30),
    notes VARCHAR(2000),
    CONSTRAINT chk_maintenance_history_action CHECK (action IN (
        'ACCEPTED', 'VENDOR_UPDATED', 'PROCESSING_STARTED', 'REPAIR_COMPLETED',
        'VERIFIED', 'REPAIR_REJECTED', 'CLEANING_COMPLETED')),
    CONSTRAINT chk_maintenance_history_previous CHECK (previous_status IN (
        'CHO_TIEP_NHAN', 'DA_TIEP_NHAN', 'DANG_XU_LY', 'CHO_XAC_NHAN', 'CHO_VE_SINH', 'HOAN_TAT')),
    CONSTRAINT chk_maintenance_history_new CHECK (new_status IN (
        'CHO_TIEP_NHAN', 'DA_TIEP_NHAN', 'DANG_XU_LY', 'CHO_XAC_NHAN', 'CHO_VE_SINH', 'HOAN_TAT'))
);
CREATE INDEX idx_maintenance_history_request_time
    ON maintenance_request_history (maintenance_request_id, occurred_at, id);
CREATE INDEX idx_maintenance_requests_open_room
    ON maintenance_requests (room_id) WHERE status <> 'HOAN_TAT';

