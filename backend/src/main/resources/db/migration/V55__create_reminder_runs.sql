CREATE TABLE reminder_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Thời điểm thực tế; giao diện sẽ hiển thị theo giờ Việt Nam.
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,

    -- Ngày "hôm nay" dùng để tính ngày nhận phòng.
    processing_date DATE NOT NULL,
    check_in_date DATE NOT NULL,

    -- SCHEDULED: chạy định kỳ; MANUAL: kích hoạt trên quản trị.
    trigger_type VARCHAR(20) NOT NULL,

    -- RUNNING, COMPLETED, COMPLETED_WITH_ERRORS, FAILED.
    status VARCHAR(30) NOT NULL,

    selected_count INTEGER NOT NULL DEFAULT 0,
    sent_count INTEGER NOT NULL DEFAULT 0,
    skipped_count INTEGER NOT NULL DEFAULT 0,
    failed_count INTEGER NOT NULL DEFAULT 0,

    -- Lỗi khiến cả lượt chạy không hoàn tất.
    error_message VARCHAR(1000),

    CONSTRAINT ck_reminder_runs_trigger
        CHECK (trigger_type IN ('SCHEDULED', 'MANUAL')),

    CONSTRAINT ck_reminder_runs_status
        CHECK (
            status IN (
                'RUNNING',
                'COMPLETED',
                'COMPLETED_WITH_ERRORS',
                'FAILED'
            )
        ),

    CONSTRAINT ck_reminder_runs_counts
        CHECK (
            selected_count >= 0
            AND sent_count >= 0
            AND skipped_count >= 0
            AND failed_count >= 0
        ),

    CONSTRAINT ck_reminder_runs_check_in_date
        CHECK (check_in_date = processing_date + 1)
);

CREATE INDEX idx_reminder_runs_started
    ON reminder_runs (started_at DESC, id DESC);

CREATE INDEX idx_reminder_runs_scheduled_date
    ON reminder_runs (processing_date, trigger_type);

-- Email cũ và email huỷ không thuộc lượt nhắc mới sẽ để NULL.
ALTER TABLE email_logs
    ADD COLUMN reminder_run_id BIGINT;

ALTER TABLE email_logs
    ADD CONSTRAINT fk_email_logs_reminder_run
    FOREIGN KEY (reminder_run_id) REFERENCES reminder_runs (id);

CREATE INDEX idx_email_logs_reminder_run
    ON email_logs (reminder_run_id);