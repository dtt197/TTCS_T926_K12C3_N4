CREATE TABLE maintenance_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    severity VARCHAR(20) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'CHO_TIEP_NHAN',
    reported_by BIGINT NOT NULL,
    reported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idempotency_key UUID NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    CONSTRAINT fk_maintenance_requests_room
        FOREIGN KEY (room_id) REFERENCES rooms (id),
    CONSTRAINT fk_maintenance_requests_reported_by
        FOREIGN KEY (reported_by) REFERENCES users (id),
    CONSTRAINT uq_maintenance_requests_idempotency_key
        UNIQUE (idempotency_key),
    CONSTRAINT chk_maintenance_requests_severity
        CHECK (severity IN ('NHE', 'NGHIEM_TRONG')),
    CONSTRAINT chk_maintenance_requests_description
        CHECK (btrim(description) <> ''),
    CONSTRAINT chk_maintenance_requests_status
    CHECK (status IN (
        'CHO_TIEP_NHAN',
        'DANG_XU_LY',
        'CHO_XAC_NHAN',
        'HOAN_TAT'
    )),
    CONSTRAINT chk_maintenance_requests_request_hash
        CHECK (request_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_maintenance_requests_room_id_reported_at
    ON maintenance_requests (room_id, reported_at);
CREATE INDEX idx_maintenance_requests_status_reported_at
    ON maintenance_requests (status, reported_at);
