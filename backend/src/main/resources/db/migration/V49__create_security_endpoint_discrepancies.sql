CREATE TABLE security_endpoint_discrepancies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint_method VARCHAR(10) NOT NULL,
    endpoint_path VARCHAR(512) NOT NULL,
    approved_access VARCHAR(20) NOT NULL,
    approved_roles VARCHAR(100) NOT NULL DEFAULT '',
    actual_access VARCHAR(20) NOT NULL,
    actual_roles VARCHAR(100) NOT NULL DEFAULT '',
    description VARCHAR(2000) NOT NULL,
    assignee_id BIGINT NOT NULL REFERENCES users(id),
    created_by_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_security_discrepancy_method
        CHECK (endpoint_method IN ('GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS', 'TRACE')),
    CONSTRAINT chk_security_discrepancy_approved_access
        CHECK (approved_access IN ('PUBLIC', 'AUTHENTICATED', 'ROLES', 'DENIED')),
    CONSTRAINT chk_security_discrepancy_actual_access
        CHECK (actual_access IN ('PUBLIC', 'AUTHENTICATED', 'ROLES', 'DENIED')),
    CONSTRAINT chk_security_discrepancy_description
        CHECK (btrim(description) <> '')
);

CREATE INDEX idx_security_discrepancies_endpoint
    ON security_endpoint_discrepancies (endpoint_method, endpoint_path, created_at DESC);
